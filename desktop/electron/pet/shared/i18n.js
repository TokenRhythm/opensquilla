  const DICT = { zh, en, ja };

  let lang = 'zh';

  function setLang(next) {
    lang = LANGS.includes(next) ? next : 'zh';
    return lang;
  }

  function getLang() { return lang; }

  function fill(str, vars) {
    if (!vars) return str;
    return str.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined || vars[k] === null ? '' : String(vars[k])));
  }

  // Missing keys fall back to zh, then to the key itself — a half-translated
  // build degrades to Chinese rather than to blank labels.
  function t(key, vars) {
    const table = DICT[lang] || DICT.zh;
    const raw = table[key] !== undefined ? table[key] : DICT.zh[key];
    if (raw === undefined) return key;
    return fill(raw, vars);
  }

  return { LANGS, DICT, t, setLang, getLang };
